import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync('index.html','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));
const start=html.indexOf('<script>')+8,end=html.indexOf('</script>',start);
assert.ok(start>=8&&end>start,'Game script exists');
const js=html.slice(start,end);new Function(js);
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(new Set(ids).size,ids.length,'IDs are unique');
for(const id of ['world','score','distance','coins','delivery','menu','play','pause','pauseScreen','resume','gameover','again','home'])assert.ok(ids.includes(id),'Missing game UI: '+id);
for(const term of ['MARKET RUSH','function startRun','function finishRun','function act','function update','function drawBackground','function drawPlayer','pointerdown','pointerup','ArrowLeft','ArrowRight','ArrowUp','ArrowDown','nmrBest','nmrCoins'])assert.ok(html.includes(term),'Missing game feature: '+term);
assert.ok(!html.includes('id="shelves"')&&!html.includes('function scramble()'),'Old sorting gameplay must not remain in the new game');
assert.equal(manifest.name,'Nazeef Bazar: Market Rush');
assert.equal(manifest.orientation,'portrait');
assert.ok(sw.includes('nazeef-market-rush-v1'),'Service worker cache must be versioned for the new game');
assert.ok(sw.includes('./index.html')&&sw.includes('./manifest.webmanifest')&&sw.includes('./icon.svg'));
assert.ok(js.includes('window.__marketRushTest'),'Browser test interface must be present');
console.log('PASS: new runner game syntax, unique UI IDs, gameplay systems, touch/keyboard controls, save keys, PWA metadata and cache version.');
